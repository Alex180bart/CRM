function buildIdentifiers(seed: ContactSeed): ContactIdentifier[] {
  const identifiers: ContactIdentifier[] = [
    {
      id: `${seed.id}_id_phone`,
      kind: "telefone",
      value: seed.phone,
      verified: true,
      primary: true,
    },
    {
      id: `${seed.id}_id_email`,
      kind: "email",
      value: seed.email,
      verified: seed.stage !== "lead",
      primary: true,
    },
  ];
  if (seed.origin === "whatsapp" || seed.stage === "cliente") {
    identifiers.push({
      id: `${seed.id}_id_wa`,
      kind: "whatsapp",
      value: seed.phone,
      verified: true,
      primary: false,
    });
  }
  if (seed.origin === "instagram") {
    identifiers.push({
      id: `${seed.id}_id_ig`,
      kind: "instagram",
      value: `@${seed.name.toLowerCase().split(" ")[0]}.${seed.id.slice(-3)}`,
      verified: false,
      primary: false,
    });
  }
  return identifiers;
}

function buildConsents(seed: ContactSeed): Consent[] {
  const marketingStatus =
    seed.stage === "inativo"
      ? "revogado"
      : seed.tags.includes("tag_vip")
        ? "concedido"
        : "concedido";

  return [
    {
      id: `${seed.id}_cs_atendimento`,
      purpose: "atendimento",
      channel: "whatsapp",
      status: "concedido",
      source: seed.origin === "form" ? "Formulário de inscrição" : "Primeiro contato pelo canal",
      legalBasis: "Execução de contrato",
      version: "v1.2",
      occurredAt: offsetIso({ days: -seed.createdDays }),
    },
    {
      id: `${seed.id}_cs_marketing`,
      purpose: "marketing",
      channel: "email",
      status: marketingStatus,
      source: seed.campaign ?? "Site — aceite de comunicações",
      legalBasis: "Consentimento",
      acceptedText:
        "Aceito receber comunicações sobre produtos e conteúdos da Contábil Aurora.",
      version: "v1.2",
      occurredAt: offsetIso({ days: -seed.createdDays + 1 }),
    },
  ];
}

